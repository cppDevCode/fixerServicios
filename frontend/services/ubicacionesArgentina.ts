export const PROVINCIAS_ARGENTINA: string[] =
    PROVINCIAS_LOCALIDADES_ARGENTINA.map((item) => item.provincia);

export const TODAS_LAS_LOCALIDADES_ARGENTINA: string[] = Array.from(
    new Set(
        PROVINCIAS_LOCALIDADES_ARGENTINA.flatMap((item) => item.localidades)
    )
).sort((a, b) => a.localeCompare(b, 'es', { sensitivity: 'base' }));

export function obtenerLocalidadesPorProvincia(provincia?: string): string[] {
    if (!provincia || !provincia.trim()) {
        return TODAS_LAS_LOCALIDADES_ARGENTINA;
    }
    const encontrada = PROVINCIAS_LOCALIDADES_ARGENTINA.find(
        (item) =>
            item.provincia.toLowerCase() === provincia.trim().toLowerCase()
    );
    return encontrada ? encontrada.localidades : TODAS_LAS_LOCALIDADES_ARGENTINA;
}

export function inferirProvinciaDeLocalidad(localidad?: string): string {
    if (!localidad || !localidad.trim()) {
        return 'Córdoba';
    }
    const buscada = localidad.trim().toLowerCase();
    const encontrada = PROVINCIAS_LOCALIDADES_ARGENTINA.find((item) =>
        item.localidades.some((loc) => loc.toLowerCase() === buscada)
    );
    return encontrada ? encontrada.provincia : 'Córdoba';
}
